"""The readable history: a markdown snapshot regenerated from the database.

TRAINER.md pays a price for choosing SQLite -- the file is a blob and its git
diffs are useless -- and buys it back here. **The DB is the truth, the snapshot
is the readable history.** The file is never hand-edited and never read back by
the engine; it exists so a person can diff it.

Two properties are the whole point, and both are load-bearing:

- **Determinism.** Nothing here depends on the clock, on insertion order or on
  anything but the rows. Regenerating against an unchanged database produces a
  byte-identical file, so `git diff` stays empty and a diff that does appear
  means something actually changed.
- **Line locality.** One exercise is one line, and its text depends only on
  that exercise. Aligning the table into columns would be prettier and would
  reflow every row the moment one name got longer, which is the same thing as
  having no diff at all.
"""

from __future__ import annotations

import json
import os
import sqlite3
from pathlib import Path

SNAPSHOT_ENV_VAR = "TRAINER_SNAPSHOT"
"""Environment variable that overrides the snapshot location."""

DEFAULT_SNAPSHOT_PARTS = ("snapshots", "catalog.md")
"""Default location, resolved against the current working directory.

Beside the database, and versioned where the database is not: `.gitignore`
excludes `*.sqlite`, and this file is what git carries instead.
"""

_COLUMNS = (
    "id",
    "name",
    "category",
    "equipment",
    "force",
    "mechanic",
    "level",
    "primary muscles",
    "secondary muscles",
    "instructions",
    "images",
)

_ABSENT = "-"
"""What an empty cell reads as. A blank one is ambiguous with a broken row."""

_PREAMBLE = """\
# Catalog snapshot

<!-- Generated by `trainer db snapshot`. Do not edit by hand: the database is
     the truth and this file is the readable history of it, so an edit here is
     lost the next time the command runs. -->

The exercise catalog as it stands in the database, one exercise per row.
`instructions` and `images` are counts rather than text: this file is for
reading, not a second copy of the database. Either is fetched by id.

{total} exercises, at {schema}.
"""


def snapshot_path() -> Path:
    """Where the snapshot for this process belongs.

    `TRAINER_SNAPSHOT` wins when set, for the same reason `TRAINER_DB` does:
    a throwaway run must not overwrite the file the repo is carrying.
    """
    override = os.environ.get(SNAPSHOT_ENV_VAR)
    if override:
        return Path(override).expanduser()
    return Path.cwd().joinpath(*DEFAULT_SNAPSHOT_PARTS)


def render(connection: sqlite3.Connection) -> str:
    """The whole snapshot as text, ending in a newline.

    Ordered by `id`: it is the primary key, so the order is total and no two
    runs can disagree about it. Ordering by name would move an exercise to a
    different line whenever it was renamed, turning one edit into two.
    """
    schema = _schema_version(connection)
    rows = connection.execute(
        """
        SELECT id, name, category, equipment, force, mechanic, level,
               primary_muscles, secondary_muscles, instructions, images
        FROM exercises ORDER BY id
        """
    ).fetchall()

    lines = [
        _PREAMBLE.format(
            schema=f"schema version {schema}" if schema else "no schema version",
            total=len(rows),
        ),
        _row(_COLUMNS),
        _row(("---",) * len(_COLUMNS)),
    ]
    lines.extend(_row(_cells(row)) for row in rows)
    return "\n".join(lines) + "\n"


def write(connection: sqlite3.Connection, path: Path) -> bool:
    """Regenerate the snapshot at `path`. True if the file changed.

    An unchanged file is left alone rather than rewritten with identical bytes:
    the content would be the same either way, but leaving the mtime alone keeps
    every tool that watches the file quiet too.
    """
    text = render(connection).encode("utf-8")
    if path.is_file() and path.read_bytes() == text:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    # Binary, so the newlines written are the newlines chosen. Text mode
    # translates them to CRLF on Windows, and a snapshot regenerated on the
    # other platform would then diff on every single line.
    path.write_bytes(text)
    return True


def _schema_version(connection: sqlite3.Connection) -> int:
    """Read here rather than imported from `migrations`.

    The snapshot describes the database in front of it, and asking the
    migration set on disk would report what this checkout could do instead.
    """
    exists = connection.execute(
        "SELECT 1 FROM sqlite_master WHERE type = 'table' AND name = 'schema_migrations'"
    ).fetchone()
    if exists is None:
        return 0
    row = connection.execute(
        "SELECT MAX(version) AS version FROM schema_migrations"
    ).fetchone()
    return int(row["version"]) if row["version"] is not None else 0


def _cells(row: sqlite3.Row) -> tuple[str, ...]:
    return (
        row["id"],
        row["name"],
        row["category"],
        row["equipment"] or _ABSENT,
        row["force"] or _ABSENT,
        row["mechanic"] or _ABSENT,
        row["level"],
        _joined(row["primary_muscles"]),
        _joined(row["secondary_muscles"]),
        str(len(json.loads(row["instructions"]))),
        str(len(json.loads(row["images"]))),
    )


def _joined(stored: str) -> str:
    values = json.loads(stored)
    return ", ".join(str(value) for value in values) if values else _ABSENT


def _row(cells: tuple[str, ...]) -> str:
    """One markdown row, unpadded -- see the note on line locality above."""
    return "| " + " | ".join(_escaped(cell) for cell in cells) + " |"


def _escaped(cell: str) -> str:
    """Make a value safe to put between two pipes.

    Both substitutions defend the same invariant -- one exercise is one line,
    and its text depends on nothing but that exercise. A pipe would silently
    become a column boundary; a newline would split one exercise across
    several rows, and every diff below it would then be off by one.
    """
    flattened = cell.replace("\r\n", " ").replace("\n", " ").replace("\r", " ")
    return flattened.replace("|", r"\|")
